"""Builds the README logo: the app icon beside the wordmark and tagline.

The text is turned into outlines so the SVG looks the same everywhere, including on
GitHub, which shows SVGs as images and never loads web fonts. Writes a light and a dark
variant to docs/.

Run from the repository root:  pip install fonttools && python3 tools/build-readme-logo.py
"""

import re
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "shared/fonts/res/font"

ICON = 128
GAP = 28
HEIGHT = 128


def text_path(font_file: str, text: str, size: float, x: float, baseline: float):
    """SVG path data for `text`, starting at x on the given baseline, and its width."""
    font = TTFont(FONTS / font_file)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    pen = SVGPathPen(glyphs)
    cursor = 0.0
    for char in text:
        name = cmap[ord(char)]
        # Font units point up; SVG points down.
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x + cursor * scale, baseline)))
        cursor += glyphs[name].width
    return pen.getCommands(), cursor * scale


def icon_body() -> str:
    svg = (ROOT / "web/static/icon.svg").read_text()
    return re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()


def build(title: str, tagline: str) -> str:
    x = ICON + GAP
    name, name_width = text_path("nunito_black.ttf", "Mangiamundo", 64, x, 76)
    line, line_width = text_path("nunito_bold.ttf", "Eat the world, start with your city", 25, x + 2, 114)
    width = round(x + max(name_width, line_width) + 4)
    scale = ICON / 512
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {HEIGHT}" width="{width}" height="{HEIGHT}" role="img" aria-label="Mangiamundo: eat the world, start with your city">
<!-- Generated by tools/build-readme-logo.py -->
<g transform="scale({scale})">
{icon_body()}
</g>
<path fill="{title}" d="{name}"/>
<path fill="{tagline}" d="{line}"/>
</svg>
"""


if __name__ == "__main__":
    out = ROOT / "docs"
    out.mkdir(exist_ok=True)
    (out / "logo.svg").write_text(build("#17324D", "#5B6B7C"))
    (out / "logo-dark.svg").write_text(build("#EEF3F8", "#9DB0C2"))
    print("wrote docs/logo.svg and docs/logo-dark.svg")
